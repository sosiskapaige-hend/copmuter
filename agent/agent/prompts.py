def _truncate(text: str, limit: int, label: str) -> str:
    if not text:
        return text
    if len(text) <= limit:
        return text
    return text[:limit].rstrip() + f"\n... [усечено: {label}]"


def build_context(platform_summary: str, memory_context: str,
                  tools_brief: str, plan_text: str = "", done_text: str = "") -> str:
    parts = [SYSTEM_IDENTITY, "", "## Среда", _truncate(platform_summary, 1800, "среда")]
    if memory_context:
        parts += ["", "## Память", _truncate(memory_context, 1800, "память")]
    if plan_text:
        parts += ["", "## План (текущий)", _truncate(plan_text, 2200, "план")]
    if done_text:
        parts += ["", "## Уже выполнено", _truncate(done_text, 2500, "выполнено")]
    parts += ["", "## Инструменты", _truncate(tools_brief, 3500, "инструменты")]
    text = "\n".join(parts)
    return _truncate(text, 12000, "контекст")


